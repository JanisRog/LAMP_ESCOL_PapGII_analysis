"""Clinical E. coli isolates: phylogroup, uidA LF primer mismatches and time to threshold (TTT).

Phylogroups: EzClermont on the clinical assemblies (data/lamp_phylogroups.tsv; one isolate per sample).
Mismatches: results/primer_screen/lamp/site_mismatches.tsv (uidA). TTT: results/cfu_ttt (uidA, >= 3-fold).
Detected = TTT <= 30 min. Tests: Fisher's exact (detection, B2 vs non-B2), Spearman (TTT vs LF mismatches),
also restricted to single-species cultures because mixed cultures are a confounder.

Output: results/clinical_phylogroups/{isolates.tsv, summary.txt, README.md}
"""
import pandas as pd
from scipy.stats import fisher_exact, spearmanr

from lamp_common import DATA, RESULTS, TIME_THRESHOLD, write_readme


def main():
    out = RESULTS / "clinical_phylogroups"; out.mkdir(parents=True, exist_ok=True)
    m = pd.read_csv(RESULTS / "primer_screen" / "lamp" / "site_mismatches.tsv", sep="\t")
    m = m[(m.target == "uidA") & ~m.genome.str.endswith("_2")].copy()
    m["sample_id"] = m.genome.str.replace("_1", "", regex=False)
    lf = m[m.site == "LF"].set_index("sample_id")[["mismatches", "mismatches_3prime"]]
    lf.columns = ["LF_mismatches", "LF_mismatches_3prime"]
    e = (pd.read_csv(RESULTS / "cfu_ttt" / "ecoli_time_to_threshold.tsv", sep="\t")
         .merge(pd.read_csv(DATA / "lamp_phylogroups.tsv", sep="\t"), on="sample_id")
         .merge(lf, left_on="sample_id", right_index=True, how="left"))
    e["detected"] = e.ttt_uidA.le(TIME_THRESHOLD["uidA"])
    e["b2"] = e.phylogroup.eq("B2")
    lines = ["Detection by phylogroup"]
    g = e.groupby("phylogroup").agg(n=("sample_id", "size"), detected=("detected", "sum"),
                                    ttt_median=("ttt_uidA", "median"))
    lines += ["  " + l for l in g.to_string().splitlines()]
    t = [[int(e[e.b2].detected.sum()), int((~e[e.b2].detected).sum())],
         [int(e[~e.b2].detected.sum()), int((~e[~e.b2].detected).sum())]]
    lines.append(f"  B2 detected/missed {t[0]}, non-B2 {t[1]}; Fisher p = {fisher_exact(t)[1]:.3f}")
    e["LF_class"] = pd.cut(e.LF_mismatches, [-1, 0, 1, 99], labels=["0", "1", ">=2"])
    lines.append("Detection by uidA LF mismatches")
    g = e.groupby("LF_class", observed=True).agg(n=("sample_id", "size"), detected=("detected", "sum"),
                                                 ttt_median=("ttt_uidA", "median"), mixed=("mixed_culture", "sum"))
    lines += ["  " + l for l in g.to_string().splitlines()]
    x = e.dropna(subset=["ttt_uidA", "LF_mismatches"])
    r, p = spearmanr(x.ttt_uidA, x.LF_mismatches)
    lines.append(f"  Spearman TTT vs LF mismatches: rho = {r:.2f}, p = {p:.3f} (n = {len(x)})")
    pure = x[x.mixed_culture == 0]
    r, p = spearmanr(pure.ttt_uidA, pure.LF_mismatches)
    lines.append(f"  single-species cultures only: rho = {r:.2f}, p = {p:.3f} (n = {len(pure)})")
    cols = ["sample_id", "phylogroup", "cfu_ml", "culture_maldi", "mixed_culture", "LF_mismatches",
            "LF_mismatches_3prime", "ttt_uidA", "detected"]
    e[cols].sort_values("ttt_uidA").to_csv(out / "isolates.tsv", sep="\t", index=False)
    (out / "summary.txt").write_text("\n".join(lines) + "\n")
    write_readme(out, """
# Clinical isolates: phylogroup, LF mismatches and time to threshold

Generated by `scripts/clinical_phylogroups.py`.

- isolates.tsv – the 38 E. coli culture-positive urines: Clermont phylogroup (EzClermont; EC_control_fail = E. coli
  control check failed, phylogroup not assigned), culture, mismatches of the uidA LF binding site to the primer
  (total and within the 3'-terminal 5 nt; empty = target absent), uidA time to threshold, detected (<= 30 min)
- summary.txt – detection by phylogroup (Fisher's exact, B2 vs non-B2) and by LF mismatches (Spearman, overall and
  single-species cultures only)
""")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
