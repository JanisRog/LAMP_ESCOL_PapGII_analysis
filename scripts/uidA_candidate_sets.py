"""Supplementary table: in silico comparison of the five uidA primer sets proposed by the NEB LAMP Primer Design Tool
(input: full uidA of E. coli 700223-20; set ID 11 = selected, top-ranked by primer-dimer dG).

Core primers only (F3, F2, F1c, B1c, B2, B3; the tool proposes loop primers separately). Per genome
(results/gene_scan/uidA): intact = all six sites without variant; critical = variant in the 3'-terminal 5 nt of
F2 or B2, or >= 2 variants in one inner site (F2, F1c, B1c, B2); minor = any other variant; incomplete = the
set's region not fully covered; absent = no uidA hit. Variants are called against 700223-20, from which all
candidate primers were designed (no primer/template differences).

Output: results/uidA_candidate_sets/{candidate_sets.tsv, README.md}
"""
import pandas as pd

from lamp_common import RESULTS, write_readme

# NEB output (1-based uidA coordinates; strand '+' = primer has the sense sequence, its 3' end = end coordinate)
CANDIDATES = {
    11: dict(dimer_dG=-1.63, F3=(843, 862, "+"), F2=(866, 885, "+"), F1c=(920, 941, "-"), B1c=(951, 971, "+"),
             B2=(1013, 1031, "-"), B3=(1047, 1066, "-")),
    20: dict(dimer_dG=-2.05, F3=(939, 958, "+"), F2=(959, 976, "+"), F1c=(1001, 1022, "-"), B1c=(1050, 1069, "+"),
             B2=(1103, 1122, "-"), B3=(1127, 1144, "-")),
    17: dict(dimer_dG=-2.12, F3=(929, 946, "+"), F2=(949, 968, "+"), F1c=(998, 1019, "-"), B1c=(1050, 1069, "+"),
             B2=(1103, 1122, "-"), B3=(1127, 1144, "-")),
    37: dict(dimer_dG=-2.34, F3=(1159, 1176, "+"), F2=(1192, 1211, "+"), F1c=(1232, 1252, "-"), B1c=(1261, 1281, "+"),
             B2=(1318, 1337, "-"), B3=(1347, 1364, "-")),
    51: dict(dimer_dG=-2.40, F3=(1407, 1426, "+"), F2=(1428, 1447, "+"), F1c=(1475, 1496, "-"), B1c=(1519, 1539, "+"),
             B2=(1576, 1593, "-"), B3=(1598, 1616, "-")),
}
INNER, INITIATING, END_NT = {"F2", "F1c", "B1c", "B2"}, {"F2", "B2"}, 5


def main():
    scan = RESULTS / "gene_scan" / "uidA"
    out = RESULTS / "uidA_candidate_sets"; out.mkdir(parents=True, exist_ok=True)
    cov = pd.read_csv(scan / "genome_coverage.tsv", sep="\t")
    var = pd.read_csv(scan / "genome_variants.tsv", sep="\t", keep_default_na=False)
    vpos = var.groupby("genome").position.apply(list).to_dict()
    rows = []
    for sid, c in CANDIDATES.items():
        sites = {k: v for k, v in c.items() if k != "dimer_dG"}
        lo, hi = min(s for s, _, _ in sites.values()), max(e for _, e, _ in sites.values())
        n = dict(intact=0, minor=0, critical=0, incomplete=0, absent=0)
        site_mm = {k: 0 for k in sites}
        for _, g in cov.iterrows():
            if pd.isna(g.qstart): n["absent"] += 1; continue
            if g.qstart > lo or g.qend < hi: n["incomplete"] += 1; continue
            P, crit, anymm = vpos.get(g.genome, []), False, False
            for k, (s, e, o) in sites.items():
                k_mm = sum(s <= p <= e for p in P)
                zone = range(e - END_NT + 1, e + 1) if o == "+" else range(s, s + END_NT)
                site_mm[k] += k_mm > 0; anymm |= k_mm > 0
                crit |= (k in INITIATING and any(p in zone for p in P)) or (k in INNER and k_mm >= 2)
            n["critical" if crit else "minor" if anymm else "intact"] += 1
        total = len(cov)
        rows.append(dict(set_id=sid, selected=int(sid == 11), dimer_dG=c["dimer_dG"], region=f"{lo}-{hi}",
                         genomes=total, **n, no_critical_pct=round(100 * (n["intact"] + n["minor"]) / total, 1),
                         intact_pct=round(100 * n["intact"] / total, 1), critical_pct=round(100 * n["critical"] / total, 1),
                         **{f"genomes_mm_{k}": v for k, v in site_mm.items()}))
    t = pd.DataFrame(rows)
    t.to_csv(out / "candidate_sets.tsv", sep="\t", index=False)
    write_readme(out, """
# uidA primer-set candidates (NEB LAMP Primer Design Tool)

Generated by `scripts/uidA_candidate_sets.py` from `results/gene_scan/uidA` (738 UPEC genomes).

- candidate_sets.tsv – one row per candidate set (set_id as given by the tool; selected = set used in this study):
  primer-dimer dG, region in uidA (F3 start to B3 end), genome counts per status (intact / minor / critical /
  incomplete / absent; core primers F3, F2, F1c, B1c, B2, B3 only), percentages, and per site the number of
  genomes with >= 1 variant. Status rules: see the script docstring.
""")
    print(t[["set_id", "region", "dimer_dG", "intact", "minor", "critical", "no_critical_pct", "intact_pct",
             "critical_pct"]].to_string(index=False))


if __name__ == "__main__":
    main()
