"""Time to threshold (TTT) of the clinical LAMP assays in relation to bacterial load, papGII status,
mixed culture and primer set.

Analyses
1. uidA TTT in E. coli culture-positive urines by semi-quantitative load (10^4 vs >= 10^5 CFU/ml).
2. uidA TTT by papGII status (all, and within >= 10^5 CFU/ml).
3. Paired comparison of papGII vs uidA TTT in papGII-positive urines (primer-set kinetics).
4. uidA TTT in mixed vs single-species cultures.
5. TTT ranges of reference-positive and reference-negative samples per target (overlap with
   nonspecific amplification).
Tests: Mann-Whitney U (two-sided) for independent groups, exact Wilcoxon signed-rank for paired data.
Samples that never crossed the threshold are excluded from TTT summaries and counted separately.

Output: results/cfu_ttt/{ecoli_time_to_threshold.tsv, summary.txt, README.md}
"""
import pandas as pd
from scipy.stats import mannwhitneyu, wilcoxon

from lamp_common import FOLD_CHANGE, RESULTS, TIME_THRESHOLD, load_samples, write_readme


def describe(x):
    never = int(x.isna().sum()); x = x.dropna()
    return (f"n={len(x) + never} median={x.median():.1f} IQR={x.quantile(.25):.1f}-{x.quantile(.75):.1f} "
            f"range={x.min():.0f}-{x.max():.0f} never_crossed={never}")


def mwu(a, b):
    return mannwhitneyu(a.dropna(), b.dropna(), alternative="two-sided").pvalue


def main():
    out = RESULTS / "cfu_ttt"
    out.mkdir(parents=True, exist_ok=True)
    s = load_samples()
    ec = s[s.ecoli == 1].copy()
    lines = []

    lines.append("1. uidA TTT by bacterial load (E. coli culture-positive urines)")
    lo, hi = ec[ec.cfu_ml == 1e4].ttt_uidA, ec[ec.cfu_ml >= 1e5].ttt_uidA
    lines += [f"  10^4 CFU/ml: {describe(lo)}", f"  >=10^5 CFU/ml: {describe(hi)}", f"  Mann-Whitney p = {mwu(lo, hi):.3f}"]

    lines.append("2. uidA TTT by papGII status")
    for label, sub in (("all loads", ec), (">=10^5 CFU/ml", ec[ec.cfu_ml >= 1e5])):
        pos, neg = sub[sub.wgs_papGII == 1].ttt_uidA, sub[sub.wgs_papGII == 0].ttt_uidA
        lines += [f"  {label}: papGII+ {describe(pos)}", f"  {label}: papGII- {describe(neg)}",
                  f"  {label}: Mann-Whitney p = {mwu(pos, neg):.3f}"]

    lines.append("3. papGII vs uidA primer set in papGII-positive urines (paired)")
    pg = ec[ec.wgs_papGII == 1]
    diff = pg.ttt_uidA - pg.ttt_papGII
    lines += [f"  papGII primers: {describe(pg.ttt_papGII)}", f"  uidA primers:   {describe(pg.ttt_uidA)}",
              f"  papGII earlier in {(diff > 0).sum()}/{len(diff)}; median difference {diff.median():.1f} min; "
              f"exact Wilcoxon p = {wilcoxon(pg.ttt_uidA, pg.ttt_papGII, method='exact').pvalue:.3f}"]

    lines.append("4. uidA TTT in mixed vs single-species cultures")
    mix, single = ec[ec.mixed_culture == 1].ttt_uidA, ec[ec.mixed_culture == 0].ttt_uidA
    lines += [f"  mixed: {describe(mix)}", f"  single: {describe(single)}"]

    lines.append("5. TTT of reference-positive vs reference-negative samples")
    for target, ref in (("uidA", "ecoli"), ("papGII", "wgs_papGII")):
        t = s[f"ttt_{target}"]
        pos, neg = t[s[ref] == 1], t[s[ref] == 0]
        late = (neg.dropna() > TIME_THRESHOLD[target]).sum()
        lines += [f"  {target} positives: {describe(pos)}",
                  f"  {target} negatives crossing: {describe(neg)}; earliest {neg.min():.0f} min; "
                  f"crossing after the {TIME_THRESHOLD[target]}-min threshold: {late}"]

    cols = ["sample_id", "cfu_ml", "culture_maldi", "mixed_culture", "wgs_papGII", "ttt_uidA", "ttt_papGII"]
    ec[cols].sort_values("ttt_uidA").to_csv(out / "ecoli_time_to_threshold.tsv", sep="\t", index=False)
    (out / "summary.txt").write_text("\n".join(lines) + "\n")
    write_readme(out, f"""
# Time to threshold vs bacterial load, papGII status and primer set

Generated by `scripts/cfu_time_to_threshold.py` from `data/all_measurements_*.csv` and `data/sample_metadata.csv`.
TTT = first minute with fluorescence >= {FOLD_CHANGE}-fold of cycle 1 (empty = never crossed within 40 min).

- ecoli_time_to_threshold.tsv – the 38 E. coli culture-positive urines: semi-quantitative load (cfu_ml),
  culture result (MALDI-TOF; comma = mixed culture), papGII by WGS, TTT for both primer sets
- summary.txt – group summaries (median, IQR, range, never crossed) and tests (Mann-Whitney U, exact Wilcoxon)
""")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
