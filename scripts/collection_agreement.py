"""Agreement between the UPEC collection and the NCBI RefSeq genomes in uidA primer-site mismatches.

For every phylogroup with >= MIN_GROUP genomes in BOTH collections and every binding site, the proportion of genomes
(amplicon region present) with >= 1 mismatch to the primer is computed per collection. Agreement is summarised by
Spearman's and Pearson's correlation across the phylogroup x site cells and by the absolute difference in percentage
points.

Output: results/collection_agreement/{cells.tsv, summary.txt, README.md}
"""
import numpy as np
import pandas as pd
from scipy.stats import pearsonr, spearmanr

from fig_primer_lollipop import ORDER, uida_long
from fig_primer_map import MIN_GROUP, NAMED
from lamp_common import RESULTS, write_readme


def main():
    out = RESULTS / "collection_agreement"; out.mkdir(parents=True, exist_ok=True)
    long = uida_long()
    n = long.groupby(["collection", "phylogroup"]).genome.nunique().unstack(0)
    groups = sorted(g for g in n.index if g in NAMED and (n.loc[g] >= MIN_GROUP).all())
    share = (long.assign(any=long.mismatches > 0).groupby(["collection", "phylogroup", "site"])["any"].mean() * 100).unstack()[ORDER]
    cells = pd.DataFrame({c: share.loc[c].loc[groups].stack() for c in ("UPEC", "NCBI")})
    cells["difference_pp"] = cells.UPEC - cells.NCBI
    cells.index.names = ["phylogroup", "site"]
    cells.round(1).to_csv(out / "cells.tsv", sep="\t")
    rho, p_rho = spearmanr(cells.UPEC, cells.NCBI)
    r, p_r = pearsonr(cells.UPEC, cells.NCBI)
    d = cells.difference_pp.abs()
    lines = [f"phylogroups with >= {MIN_GROUP} genomes in both collections: {', '.join(groups)} (cells = {len(cells)})",
             f"Spearman rho = {rho:.2f} (p = {p_rho:.1e}); Pearson r = {r:.2f}",
             f"absolute difference in the share of genomes with >= 1 mismatch: median {d.median():.1f} pp, "
             f"maximum {d.max():.0f} pp",
             "largest differences: " + "; ".join(f"{g}/{s} {v:+.0f}" for (g, s), v in
                                                  cells.difference_pp.reindex(d.sort_values(ascending=False).index[:6]).items())]
    (out / "summary.txt").write_text("\n".join(lines) + "\n")
    write_readme(out, f"""
# Agreement between the UPEC collection and the NCBI RefSeq genomes

Generated by `scripts/collection_agreement.py`.

- cells.tsv – per phylogroup (>= {MIN_GROUP} genomes in both collections) and uidA binding site: % of genomes with >= 1 mismatch
  to the primer in the UPEC collection and in the NCBI genomes, and the difference (UPEC - NCBI, percentage points)
- summary.txt – Spearman and Pearson correlation across the cells and the distribution of the differences
""")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
