"""Diagnostic accuracy of the uidA and papGII LAMP assays with exact 95% confidence intervals.

A sample is LAMP-positive if its fluorescence reaches >= 3-fold of the first cycle within the target's
time threshold (uidA 30 min, papGII 23 min). References: culture + MALDI-TOF (E. coli), WGS (papGII).
Confidence intervals: Clopper-Pearson (exact binomial).

Output: results/diagnostic_metrics/{confusion_counts.tsv, metrics_ci.tsv, README.md}
"""
import pandas as pd
from scipy.stats import beta

from lamp_common import FOLD_CHANGE, RESULTS, TIME_THRESHOLD, load_samples, write_readme

REFERENCE = {"uidA": "ecoli", "papGII": "wgs_papGII"}


def clopper_pearson(x, n, alpha=0.05):
    lo = 0.0 if x == 0 else beta.ppf(alpha / 2, x, n - x + 1)
    hi = 1.0 if x == n else beta.ppf(1 - alpha / 2, x + 1, n - x)
    return lo, hi


def main():
    out = RESULTS / "diagnostic_metrics"
    out.mkdir(parents=True, exist_ok=True)
    s = load_samples()
    counts, metrics = [], []
    for target, ref in REFERENCE.items():
        lamp = (s[f"ttt_{target}"] <= TIME_THRESHOLD[target]).astype(int)
        tp = int(((lamp == 1) & (s[ref] == 1)).sum()); fn = int(((lamp == 0) & (s[ref] == 1)).sum())
        fp = int(((lamp == 1) & (s[ref] == 0)).sum()); tn = int(((lamp == 0) & (s[ref] == 0)).sum())
        counts.append(dict(target=target, time_threshold_min=TIME_THRESHOLD[target], fold_change=FOLD_CHANGE,
                           TP=tp, FN=fn, FP=fp, TN=tn, n=tp + fn + fp + tn))
        for name, x, n in (("sensitivity", tp, tp + fn), ("specificity", tn, tn + fp),
                           ("PPV", tp, tp + fp), ("NPV", tn, tn + fn)):
            lo, hi = clopper_pearson(x, n)
            metrics.append(dict(target=target, metric=name, x=x, n=n, estimate=round(x / n, 3),
                                ci95_low=round(lo, 3), ci95_high=round(hi, 3)))
    pd.DataFrame(counts).to_csv(out / "confusion_counts.tsv", sep="\t", index=False)
    m = pd.DataFrame(metrics)
    m.to_csv(out / "metrics_ci.tsv", sep="\t", index=False)
    write_readme(out, f"""
# Diagnostic metrics with 95% CI

Generated by `scripts/diagnostic_metrics_ci.py` from `data/all_measurements_*.csv` and `data/sample_metadata.csv`.

- confusion_counts.tsv – TP/FN/FP/TN per target at the time threshold (uidA {TIME_THRESHOLD['uidA']} min,
  papGII {TIME_THRESHOLD['papGII']} min) and fluorescence >= {FOLD_CHANGE}-fold of cycle 1; n = 191 clinical urines
  (water negative control excluded). Reference: culture + MALDI-TOF for E. coli (uidA), WGS for papGII.
- metrics_ci.tsv – sensitivity = TP/(TP+FN), specificity = TN/(TN+FP), PPV = TP/(TP+FP), NPV = TN/(TN+FN);
  x/n = numerator/denominator; ci95_low/high = exact Clopper-Pearson 95% interval.
""")
    print(pd.DataFrame(counts).to_string(index=False)); print(m.to_string(index=False))


if __name__ == "__main__":
    main()
