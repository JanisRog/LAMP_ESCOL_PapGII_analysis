#!/usr/bin/env python3
"""Mismatches of the papGII LAMP binding sites to every papG gene copy (locus) in a genome collection.

Per genome: papG loci are typed as in primer_screen.py (HSPs of the PapG reference alleles >= 90% identity merged
per locus, best allele by summed bitscore, called if >= 80% of the allele is covered). For each called locus the
gene region (+ 50 nt) is extracted and, for each of the eight papGII binding sites, the fewest mismatches over all
ungapped positions on either strand are recorded (same logic as for the reference alleles in Figure 2A).

Output (in --out): locus_site_mismatches.tsv (genome, locus, allele, site, mismatches), manifest.txt, README.md
Requires BLAST+ (blastn) and primer_screen.py in the same directory.
"""
import argparse, datetime, glob, os, subprocess
from concurrent.futures import ThreadPoolExecutor

from primer_screen import PRIMERS, SPLIT, blast, rc, read_fasta, type_papg

PAD = 50


def site_sequences():
    p, k = PRIMERS["papGII"], SPLIT["papGII"]
    return {"F3": p["F3"], "F2": p["FIP"][k["FIP"]:], "LF": p["LF"], "F1c": p["FIP"][:k["FIP"]],
            "B1c": p["BIP"][:k["BIP"]], "LB": p["LB"], "B2": p["BIP"][k["BIP"]:], "B3": p["B3"]}


def best_mismatches(q, text):
    best = len(q)
    for qq in (q, rc(q)):
        n = len(qq)
        for i in range(len(text) - n + 1):
            mm = 0
            for a, b in zip(qq, text[i:i + n]):
                if a != b:
                    mm += 1
                    if mm >= best: break
            best = min(best, mm)
    return best


def scan(args):
    gid, path, papg_ref, min_id, min_cov, sites = args
    _, loci = type_papg(blast(papg_ref, path), min_id, min_cov)
    rows, contigs = [], None
    for i, locus in enumerate(l for l in loci if l["called"]):
        contigs = contigs or read_fasta(path)
        seq = contigs[locus["contig"]][max(0, locus["start"] - 1 - PAD):locus["end"] + PAD]
        for site, s in sites.items():
            rows.append((gid, i + 1, locus["best_allele"], f"{locus['contig']}:{locus['start']}-{locus['end']}",
                         site, best_mismatches(s, seq)))
    return rows


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--genomes", required=True)
    ap.add_argument("--pattern", default="*.fasta")
    ap.add_argument("--papg-ref", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--threads", type=int, default=8)
    ap.add_argument("--min-id", type=float, default=90)
    ap.add_argument("--min-cov", type=float, default=80)
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    sites = site_sequences()
    genomes = sorted(glob.glob(os.path.join(a.genomes, "**", a.pattern), recursive=True))
    jobs = [(os.path.splitext(os.path.basename(g))[0], g, a.papg_ref, a.min_id, a.min_cov, sites) for g in genomes]
    with ThreadPoolExecutor(a.threads) as ex:
        results = list(ex.map(scan, jobs))
    with open(os.path.join(a.out, "locus_site_mismatches.tsv"), "w") as fh:
        fh.write("genome\tlocus\tallele\tposition\tsite\tmismatches\n")
        for rows in results:
            for r in rows: fh.write("\t".join(map(str, r)) + "\n")
    blast_version = subprocess.run(["blastn", "-version"], capture_output=True, text=True).stdout.splitlines()[0]
    with open(os.path.join(a.out, "manifest.txt"), "w") as fh:
        fh.write(f"date: {datetime.datetime.now().isoformat(timespec='seconds')}\nscript: {os.path.abspath(__file__)}\n"
                 f"genomes: {a.genomes} ({len(genomes)} files matching {a.pattern})\npapG_reference: {a.papg_ref}\n"
                 f"{blast_version}\nlocus call: pident >= {a.min_id}, coverage >= {a.min_cov} %; region padded by {PAD} nt\n"
                 f"binding sites: {sites}\n")
    with open(os.path.join(a.out, "README.md"), "w") as fh:
        fh.write("""# papGII binding sites vs papG loci

Generated by papg_site_scan.py (inputs, thresholds and site sequences in manifest.txt).

- locus_site_mismatches.tsv – one row per called papG locus and papGII binding site: genome, locus number,
  allele (PapG-I/II/III, best match), position (contig:start-end), and the fewest mismatches of the binding-site
  sequence at any ungapped position on either strand within the locus (+ 50 nt)
""")
    print(f"done: {sum(len(r) for r in results) // len(sites)} loci in {len(genomes)} genomes")


if __name__ == "__main__":
    main()
